/* ============================================================================
   ASCII-ОБРАЗЫ КАНОНА v11 — крупные абстрактные тела для шапок разделов.

   ЧТО ЭТО. Сцена честно считается лучом (raymarching знаковых полей), а
   печатается ЗНАКАМИ: яркость точки выбирает знак из ряда — от точки до
   сплошного блока. Ни одного нового цвета: тон делает плотность знака.
   Свет один и сверху-слева, как во всём каноне.

   ПОЧЕМУ ОБРАЗЫ АБСТРАКТНЫЕ, А НЕ ПРЕДМЕТЫ. Прошлые заходы делали арку,
   рамку, лист, стопку листов. Предмет требует, чтобы его узнали, — а
   узнанный предмет тут же начинает что-то обещать («это про двери?»,
   «это про фото?») и спорит с заголовком вместо того, чтобы его держать.
   Абстрактное тело не обещает ничего и остаётся фактурой: объём, свет, тень.
   Это решение владельца, а не лень: предметные варианты были показаны и
   отвергнуты. Не возвращайте их.

   ПОЧЕМУ ТЕЛА ГЛАДКИЕ. Первый заход дробил форму на ячейки — монолит,
   рассыпающийся в облако кубиков. В цвете приём работает, в знаках нет:
   печать знаками сама по себе уже зерно, каждая клетка либо занята, либо
   пуста. Дроблёная поверхность кладёт второе зерно на первое, и вместо
   формы в кадре остаётся шум.

   КАК ПОДКЛЮЧИТЬ:
       <canvas data-ascii-figure="mobius" height="432"></canvas>
       <script src="/static/ascii-figures.js" defer></script>
   Больше ничего не нужно: полотно найдётся само, размер возьмётся из
   раскладки, палитра — из CSS-переменных канона (--lp-text, --lp-key).
   Фон прозрачный: подложку даёт страница.

   Атрибуты полотна (все необязательные):
     data-ascii-figure  mobius | vortex | blobs | gyroid | shells | column
     data-cell          зерно, px по горизонтали. По умолчанию 6 — см. «цена».
     data-angle         поворот сцены в градусах, по умолчанию 34
     data-still         присутствует → тело не вращается и не дышит

   РАСКЛАДКА ПО РАЗДЕЛАМ (решение владельца, 2026-08-23):
     главная  → mobius (лента Мёбиуса)
     картинки → gyroid
   Остальные четыре тела приложены как утверждённый запас.

   ЦЕНА КАДРА. Замер одного полотна 492×432: зерно 3 — 21 мс, 4 — 13 мс,
   5 — 8 мс, 6 — 5.8 мс, 8 — 3.3 мс. Считает ГЛАВНЫЙ ПОТОК, поэтому:
     • зерно по умолчанию 6, и опускать его ниже 5 на боевой странице нельзя —
       13 мс каждые 80 мс заметно портят прокрутку на слабой машине;
     • кадр идёт не чаще раза в 80 мс: движение медленное, 12 кадров в секунду
       от 60 на глаз не отличаются, а вентилятор отличается;
     • полотно вне экрана не считается вовсе (IntersectionObserver);
     • при prefers-reduced-motion рисуется один статичный кадр.
   Больше одного тела на экран одновременно не ставьте.
   ========================================================================== */
(function (root) {
  'use strict';

  function clamp01(v) { return v < 0 ? 0 : (v > 1 ? 1 : v); }

  // Матрица Байера 8×8 — упорядоченный дизеринг. Со случайным шумом переход
  // между ступенями знака читается грязью, с матрицей — ровным зерном.
  var B8 = (function () {
    var m = [[0, 2], [3, 1]], i, j;
    while (m.length < 8) {
      var s = m.length, r = [];
      for (i = 0; i < s * 2; i++) r.push(new Array(s * 2));
      for (i = 0; i < s; i++) for (j = 0; j < s; j++) {
        var v = m[i][j] * 4;
        r[i][j] = v; r[i][j + s] = v + 2; r[i + s][j] = v + 3; r[i + s][j + s] = v + 1;
      }
      m = r;
    }
    var out = [];
    for (i = 0; i < 8; i++) { out.push([]); for (j = 0; j < 8; j++) out[i].push(m[i][j] / 64); }
    return out;
  })();

  // Ряд знаков от пустого к плотному: индекс = ступень яркости. Ряд длиннее
  // двух ступеней превращает один бит в подобие полутона, не заводя ни одного
  // нового цвета — плотность знака и есть шкала.
  var RAMP = [' ', '\u00B7', ':', '+', '\u2592', '\u2593', '\u2588'];

  /* --- Знаковые поля расстояний. Всё скалярно и без единой аллокации: на
         каждый шаг марша приходится вызов, и объекты-векторы здесь стоят
         дороже самой математики. --------------------------------------- */
  function sdBox(x, y, z, bx, by, bz) {
    var qx = Math.abs(x) - bx, qy = Math.abs(y) - by, qz = Math.abs(z) - bz;
    var mx = qx > 0 ? qx : 0, my = qy > 0 ? qy : 0, mz = qz > 0 ? qz : 0;
    return Math.sqrt(mx * mx + my * my + mz * mz) +
           Math.min(Math.max(qx, Math.max(qy, qz)), 0);
  }
  function sdSphere(x, y, z, r) { return Math.sqrt(x * x + y * y + z * z) - r; }
  // Прямоугольник на плоскости — тот же sdBox в 2D. Нужен там, где тело
  // собрано из плоского сечения: у ленты сечение и есть форма.
  function sdBox2(x, y, bx, by) {
    var qx = Math.abs(x) - bx, qy = Math.abs(y) - by;
    var mx = qx > 0 ? qx : 0, my = qy > 0 ? qy : 0;
    return Math.sqrt(mx * mx + my * my) + Math.min(Math.max(qx, qy), 0);
  }
  // Мягкое объединение: два тела не стыкуются швом, а срастаются. k — ширина
  // перетекания. Без него капли читаются кучей отдельных шаров.
  function smin(a, b, k) {
    var h = k - Math.abs(a - b); if (h < 0) h = 0;
    return Math.min(a, b) - h * h * 0.25 / k;
  }

  /* --- СОБСТВЕННОЕ ДВИЖЕНИЕ ТЕЛА -----------------------------------------
     Вращение — движение камеры: форма при нём та же, меняется только точка
     зрения, и через полминуты смотреть уже не на что. Поэтому у каждого тела
     есть своя медленная жизнь: PH — общая фаза, и каждое поле берёт её туда,
     где у формы главный параметр. Меняется именно ПАРАМЕТР, а не положение:
     тело не ездит по кадру (это читалось бы сбоем вёрстки), оно дышит на
     месте. Амплитуды малы намеренно — движение должно быть замечено боковым
     зрением, а не отвлекать от текста. -------------------------------- */
  var PH = 0;

  var MAPS = {
    /* ЛЕНТА МЁБИУСА. Сечение — прямоугольник, который едет по окружности и за
       полный оборот успевает перевернуться на пол-оборота. Шва на стыке нет и
       быть не может: при a = ±π полуугол прыгает на π, а прямоугольник
       симметричен относительно центра — (u,v) и (−u,−v) дают одно и то же
       расстояние, поле остаётся непрерывным.
       Жизнь: точка перекрута едет по кольцу. */
    mobius: function (x, y, z) {
      var a = Math.atan2(z, x);
      var r = Math.sqrt(x * x + z * z) - 0.62;
      var ha = a * 0.5 + PH * 0.5, c = Math.cos(ha), s = Math.sin(ha);
      return sdBox2(r * c + y * s, -r * s + y * c, 0.30 + 0.05 * Math.sin(PH * 1.3), 0.028);
    },

    /* ВИХРЬ. Тело вращения: радиус стенки растёт с высотой по квадрату — внизу
       горло, вверху раструб. Поверх радиуса пущена винтовая рябь (угол минус
       высота): без неё раструб читается просто рупором, с ней — закруткой.
       Жизнь: рябь стекает по стенке вниз. */
    vortex: function (x, y, z) {
      var r = Math.sqrt(x * x + z * z);
      var t = clamp01((y + 0.78) / 1.52);
      var rw = 0.07 + 0.78 * t * t +
               0.05 * Math.cos(Math.atan2(z, x) * 3 - y * 4.2 + PH * 1.6);
      var wall = Math.abs(r - rw) - 0.030;
      return Math.max(wall, Math.abs(y) - 0.74);
    },

    /* СЛИЯНИЕ КАПЕЛЬ. Четыре массы разного размера, сросшиеся мягким
       объединением. Ключ — ширина перетекания: при малой k видны четыре шара,
       при большой всё сливается в ком без силуэта.
       Жизнь: капли ходят по маленьким окружностям с разными периодами, и
       перемычки между ними то натягиваются, то заплывают. */
    blobs: function (x, y, z) {
      var p = PH;
      var d = sdSphere(x + 0.30 + 0.10 * Math.sin(p * 0.9),
                       y + 0.14 + 0.08 * Math.cos(p * 0.7), z - 0.08, 0.40);
      d = smin(d, sdSphere(x - 0.24 - 0.09 * Math.sin(p * 1.1),
                           y - 0.16 - 0.07 * Math.cos(p * 1.3), z + 0.14, 0.34), 0.34);
      d = smin(d, sdSphere(x - 0.02, y - 0.46 - 0.09 * Math.sin(p * 0.8),
                           z - 0.20 + 0.09 * Math.cos(p * 1.0), 0.25), 0.30);
      d = smin(d, sdSphere(x - 0.46 + 0.08 * Math.cos(p * 1.2),
                           y + 0.34, z - 0.18, 0.27), 0.30);
      return d;
    },

    /* ГИРОИД. Периодическая минимальная поверхность: тело не собрано из
       деталей, а задано одним уравнением на всё пространство. Значение функции
       НЕ расстояние, поэтому делим на масштаб частоты — без нормировки марш
       перелетает стенку и поверхность рвётся. Куб обрезает бесконечный узор до
       предмета. Частота 2.5 = полтора периода в кубе; при 3.4 тело читалось не
       формой, а рябью.
       Жизнь: узор течёт сквозь неподвижный куб — кажется, что тело перебирает
       само себя, оставаясь на месте. */
    gyroid: function (x, y, z) {
      var s = 2.5, p = PH * 0.55;
      var g = Math.sin(x * s + p) * Math.cos(y * s) +
              Math.sin(y * s + p) * Math.cos(z * s) +
              Math.sin(z * s + p) * Math.cos(x * s);
      var surf = (Math.abs(g) - (0.42 + 0.12 * Math.sin(PH * 0.9))) / (s * 1.5);
      return Math.max(surf, sdBox(x, y, z, 0.70, 0.70, 0.70));
    },

    /* ВЛОЖЕННЫЕ ОБОЛОЧКИ. Четыре сферических слоя; у трёх внешних вырезана
       четверть, и в вырезе видно, что внутри ещё что-то есть. Внутренняя
       оболочка целая — иначе разрез проваливается в пустоту.
       Жизнь: слои дышат вразнобой, зазоры то сходятся, то расходятся. */
    shells: function (x, y, z) {
      var R = [0.86, 0.63, 0.42, 0.22], d = 1e9;
      for (var i = 0; i < 4; i++) {
        var rr = R[i] + 0.055 * Math.sin(PH * 0.85 + i * 1.4);
        var sh = Math.abs(sdSphere(x, y, z, rr)) - 0.024;
        // Вырез смотрит НА камеру: при повороте сцены на 34° зритель стоит со
        // стороны −x, +z, и четверть x>0 уходила бы за горизонт — снаружи это
        // выглядело просто целым шаром.
        if (i < 3) sh = Math.max(sh, Math.min(-x, y));
        if (sh < d) d = sh;
      }
      return d;
    },

    /* СКРУЧЕННАЯ КОЛОННА. Скруглённое квадратное сечение, провёрнутое по
       высоте. Поворот пространства ломает честность расстояния, поэтому шаг
       марша укорочен — иначе луч проскакивает сквозь грань.
       Жизнь: крутизна винта ходит туда-обратно. */
    column: function (x, y, z) {
      var a = y * (1.25 + 0.55 * Math.sin(PH * 0.75));
      var ca = Math.cos(a), sa = Math.sin(a);
      var rx = x * ca - z * sa, rz = x * sa + z * ca;
      return sdBox(rx, y, rz, 0.30, 0.84, 0.30) - 0.06;
    }
  };

  // Укорочённый шаг — там, где поле перестало быть честным расстоянием:
  // поворот пространства (лента, колонна), модуляция радиуса (вихрь),
  // уравнение вместо расстояния (гироид).
  var STEP = { mobius: 0.4, vortex: 0.32, blobs: 0.9, gyroid: 0.6,
               shells: 1, column: 0.4 };

  // Высота камеры: кольцевым телам нужен взгляд сверху, иначе кольцо видно с
  // ребра и читается полоской; стоячим хватает середины.
  var CAM = { mobius: 1.15, vortex: 0.72, blobs: 0.34, gyroid: 0.50,
              shells: 0.42, column: 0.26 };

  // Крупность в кадре. Тело должно занимать три четверти высоты: при 2.1 все
  // шесть висели в середине кадра как марка на конверте.
  var ZOOM = { mobius: 3.9, vortex: 3.3, blobs: 4.0, gyroid: 3.8,
               shells: 3.6, column: 3.1 };

  /* Акцент — не свечение, а ЦВЕТ: тон знака остаётся прежним, меняется только
     краска. Прежний приём (светящиеся ячейки заливались в максимум) выжигал в
     форме плоские пятна. Место акцента у каждого тела одно и осмысленное — то,
     что в форме главное. У гироида и капель акцента нет вовсе: у них нет
     выделенной части, и любая покраска там была бы произволом. */
  var TINT = {
    mobius: function (x, y, z) { return Math.atan2(z, x) > 0; },  // полвитка
    vortex: function (x, y, z) { return y < -0.30; },             // горло
    shells: function (x, y, z) { return x * x + y * y + z * z < 0.075; },
    column: function (x, y, z) { return y > 0.40; }               // верхняя треть
  };

  // Марш: шагаем ровно на расстояние до ближайшей поверхности — по построению
  // столкнуться раньше не с чем. Порог попадания растёт с дальностью, иначе на
  // далёких точках луч топчется до исчерпания шагов.
  function march(map, ox, oy, oz, dx, dy, dz, step) {
    var t = 0.02;
    for (var i = 0; i < 96; i++) {
      var d = map(ox + dx * t, oy + dy * t, oz + dz * t);
      if (d < 0.0016 * t + 0.0008) return t;
      t += d * step;
      if (t > 10) break;
    }
    return -1;
  }

  // Нормаль центральной разностью. Четыре пробы (тетраэдр) вместо шести —
  // вдвое дешевле при неразличимом на глаз результате.
  var NX = 0, NY = 0, NZ = 0;
  function normal(map, x, y, z) {
    var e = 0.0035;
    var a = map(x + e, y - e, z - e), b = map(x - e, y - e, z + e);
    var c = map(x - e, y + e, z - e), d = map(x + e, y + e, z + e);
    var nx = a - b - c + d, ny = -a - b + c + d, nz = -a + b - c + d;
    var l = Math.sqrt(nx * nx + ny * ny + nz * nz) || 1;
    NX = nx / l; NY = ny / l; NZ = nz / l;
  }

  // Мягкая тень: маршируем к свету и запоминаем, насколько близко луч прошёл
  // от геометрии. Именно она читается как «предмет стоит», а не «наклеен».
  function shadow(map, px, py, pz, lx, ly, lz) {
    var res = 1, t = 0.03;
    for (var i = 0; i < 22; i++) {
      var h = map(px + lx * t, py + ly * t, pz + lz * t);
      if (h < 0.0012) return 0;
      var k = 9 * h / t; if (k < res) res = k;
      t += Math.min(Math.max(h, 0.025), 0.3);
      if (t > 4) break;
    }
    return res < 0 ? 0 : (res > 1 ? 1 : res);
  }

  // Окклюзия: пять проб вдоль нормали. Там, где поле «не отпускает» на
  // ожидаемое расстояние, рядом есть складка — и она темнеет.
  function occl(map, px, py, pz) {
    var o = 0, s = 1;
    for (var i = 1; i <= 5; i++) {
      var h = 0.022 * i * i;
      var d = map(px + NX * h, py + NY * h, pz + NZ * h);
      o += (h - d) * s; s *= 0.72;
    }
    return clamp01(1 - 1.5 * o);
  }

  function draw(cv, ang) {
    var name = cv.dataset.asciiFigure;
    var map = MAPS[name];
    if (!map) return;
    var w = cv.clientWidth, h = cv.clientHeight;
    if (!w || !h) return;

    var dpr = Math.min(window.devicePixelRatio || 1, 2);
    cv.width = Math.round(w * dpr); cv.height = Math.round(h * dpr);
    var ctx = cv.getContext('2d');
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    // Фон прозрачный: подложку даёт страница. Своей заливкой полотно завело бы
    // вторую поверхность внутри первой — карточку, которой в каноне нет.
    ctx.clearRect(0, 0, w, h);

    var cs = getComputedStyle(cv);
    var fg  = cs.getPropertyValue('--lp-text').trim() || '#F2F5F4';
    var key = cs.getPropertyValue('--lp-key').trim() || '#3FB67C';
    var mono = cs.getPropertyValue('--font-mono').trim() ||
               '"SB Sans Cond Mono", ui-monospace, monospace';

    var step = STEP[name], tintFn = TINT[name];

    // Знакоместо НЕ квадратное: у конденсированной моноширинной ширина знака
    // примерно вдвое меньше высоты. Высоту берём от зерна, а ширину МЕРЯЕМ у
    // самого шрифта — коэффициент на глаз даёт либо щели, либо наползание.
    var cell = parseFloat(cv.dataset.cell) || 6;
    var chh = cell * 2, fs = Math.round(chh * 0.92);
    ctx.font = '700 ' + fs + 'px ' + mono;
    var cww = ctx.measureText('#').width || fs * 0.5;
    ctx.textAlign = 'center'; ctx.textBaseline = 'middle';
    var cols = Math.floor(w / cww), rows = Math.floor(h / chh);
    var top = RAMP.length - 1;

    // Камера. Поворот сцены делается один раз над лучом, а не внутри поля:
    // вращать точку на каждом шаге марша — лишние синусы там, где их считают
    // сотни тысяч раз.
    var ca = Math.cos(ang), sa = Math.sin(ang);
    var cy = CAM[name] !== undefined ? CAM[name] : 0.72, cz = 3.35;
    var ox = -cz * sa, oz = cz * ca, oy = cy;

    // Базис кадра. Знаки здесь не косметика: right = cross(forward, (0,1,0)) =
    // (−fz, 0, fx). Перепутать — значит получить кадр вверх ногами.
    var fx = -ox, fy = 0.02 - oy, fz = -oz;
    var fl = Math.sqrt(fx * fx + fy * fy + fz * fz); fx /= fl; fy /= fl; fz /= fl;
    var rx = -fz, ry = 0, rz = fx;
    var rl = Math.sqrt(rx * rx + rz * rz) || 1; rx /= rl; rz /= rl;
    var ux = ry * fz - rz * fy, uy = rz * fx - rx * fz, uz = rx * fy - ry * fx;

    var lx = -0.5, ly = 0.78, lz = 0.38;      // свет один и сверху-слева
    var ll = Math.sqrt(lx * lx + ly * ly + lz * lz); lx /= ll; ly /= ll; lz /= ll;

    var half = h / 2, zoom = ZOOM[name] !== undefined ? ZOOM[name] : 2.1;

    for (var r = 0; r < rows; r++) {
      for (var c = 0; c < cols; c++) {
        var px = (c + 0.5) * cww, py = (r + 0.5) * chh;
        var sx = (px - w / 2) / half, sy = -(py - half) / half;

        var dx = rx * sx + ux * sy + fx * zoom;
        var dy = ry * sx + uy * sy + fy * zoom;
        var dz = rz * sx + uz * sy + fz * zoom;
        var dl = Math.sqrt(dx * dx + dy * dy + dz * dz); dx /= dl; dy /= dl; dz /= dl;

        // Промах — чистый фон. Никакого «неба»: зерно по всему полотну спорит
        // с образом и превращает его в текстуру. Пусто значит пусто.
        var t = march(map, ox, oy, oz, dx, dy, dz, step);
        if (t < 0) continue;

        var hx = ox + dx * t, hy = oy + dy * t, hz = oz + dz * t;
        normal(map, hx, hy, hz);
        var dif = NX * lx + NY * ly + NZ * lz; if (dif < 0) dif = 0;
        // У тени есть дно: полная тень гасила в ноль всё, что закрыто сверху,
        // и закрытая часть пропадала из кадра целиком, а не темнела.
        var sh = 0.22 + 0.78 * shadow(map, hx + NX * 0.008, hy + NY * 0.008,
                                      hz + NZ * 0.008, lx, ly, lz);
        var ao = occl(map, hx, hy, hz);
        var sky = 0.5 + 0.5 * NY;
        var vd = -(NX * dx + NY * dy + NZ * dz); if (vd < 0) vd = 0;
        var rim = Math.pow(1 - vd, 3.2);
        var hvx = lx - dx, hvy = ly - dy, hvz = lz - dz;
        var hl = Math.sqrt(hvx * hvx + hvy * hvy + hvz * hvz) || 1;
        var sp = (NX * hvx + NY * hvy + NZ * hvz) / hl; if (sp < 0) sp = 0;

        var lum = 0.16 * sky * ao + 0.82 * dif * sh + 0.22 * rim * ao +
                  0.45 * Math.pow(sp, 26) * sh;
        if (lum > 1) lum = 1;
        // Гаммы здесь намеренно нет: подъём полутонов вместе с кривой
        // контраста ниже загонял в максимум всё освещённое хотя бы вполсилы, и
        // сфера превращалась в сплошной диск без единой ступени.
        lum *= 1 - Math.min(0.3, Math.max(0, (t - 2.8) * 0.13));

        // Кривая контраста: ровный полутон в одном бите читается грязью — глаз
        // видит зерно, а не грань. Сжимаем диапазон вокруг середины.
        var q = clamp01((lum - 0.235) / 0.527);
        lum = q * q * (3 - 2 * q);

        // Любое попадание печатается хотя бы редким зерном: силуэт держит
        // форму, тон отвечает за рельеф. Без дна теневая часть выпадала дырой.
        // Дно низкое намеренно: на 0.08 дизеринг сыпал знак в каждую вторую
        // клетку тени, и теневая половина образа читалась шумом.
        if (lum < 0.035) lum = 0.035;

        var lit = tintFn && tintFn(hx - NX * 0.012, hy - NY * 0.012, hz - NZ * 0.012);

        // Ступень выбирается с дизерингом: дробная часть сравнивается с
        // порогом. Иначе на плавном переходе видны полосы — знак меняется
        // разом по всей изолинии яркости.
        var lv = lum * top, i0 = Math.floor(lv);
        if (lv - i0 > B8[r % 8][c % 8]) i0++;
        if (i0 > top) i0 = top;
        if (i0 <= 0) continue;

        ctx.fillStyle = lit ? key : fg;
        ctx.fillText(RAMP[i0], px, py);
      }
    }
  }

  /* ===== Один общий кадр на все полотна ===================================
     Кадр идёт не чаще раза в 80 мс и только для полотен, попавших в экран.
     Оба ограничения обязательны: без первого страница отдаёт раймарчу весь
     главный поток, без второго считается образ, которого никто не видит.
     ====================================================================== */

  var figures = [], visible = new WeakSet(), raf = 0, last = 0;

  function reduced() {
    return !!(window.matchMedia &&
      window.matchMedia('(prefers-reduced-motion: reduce)').matches);
  }

  function angleOf(cv, ts) {
    var base = (parseFloat(cv.dataset.angle) || 34) * Math.PI / 180;
    if (cv.hasAttribute('data-still') || reduced()) return base;
    return (base + ts * 0.00035) % (Math.PI * 2);
  }

  function frame(ts) {
    raf = 0;
    if (ts - last < 80) { schedule(); return; }
    last = ts;
    PH = ts * 0.00042;
    var moving = false;
    for (var i = 0; i < figures.length; i++) {
      var cv = figures[i];
      if (!visible.has(cv)) continue;
      draw(cv, angleOf(cv, ts));
      if (!cv.hasAttribute('data-still')) moving = true;
    }
    if (moving && !reduced()) schedule();
  }

  function schedule() { if (!raf) raf = requestAnimationFrame(frame); }

  // Метка времени той же шкалы, что приходит в кадр анимации: у фазы дыхания и
  // у порога в 80 мс не должно быть двух разных нулей.
  function now() {
    return (window.performance && performance.now) ? performance.now() : 0;
  }

  function mount() {
    figures = [].slice.call(document.querySelectorAll('[data-ascii-figure]'));
    if (!figures.length) return;
    // Все полотна считаются видимыми ДО первого слова наблюдателя, и это не
    // перестраховка ради красоты. Наблюдатель — единственный источник
    // видимости, и там, где он молчит (старый движок, вложенный фрейм,
    // страница, снятая с раскладки), образ не появится вообще, а на его месте
    // останется дыра. Цена оптимизма — один лишний кадр на полотна за экраном:
    // первый же отчёт наблюдателя их снимет, и дальше правило «за экраном не
    // считаем» работает как задумано.
    figures.forEach(function (cv) { visible.add(cv); });
    if (typeof IntersectionObserver === 'function') {
      var io = new IntersectionObserver(function (recs) {
        recs.forEach(function (rec) {
          if (rec.isIntersecting) visible.add(rec.target);
          else visible.delete(rec.target);
        });
        schedule();
      }, { rootMargin: '96px' });
      figures.forEach(function (cv) { io.observe(cv); });
    }
    // Первый кадр рисуется СРАЗУ, а не с ближайшим кадром анимации: иначе
    // страница успевает показаться с пустотой на месте образа, и он проявляется
    // рывком уже на глазах. Дальше кадры идут обычным чередом через schedule().
    frame(now());
    // Ширина полотна зависит от раскладки, а раскладка — от окна. Своего
    // дребезга не заводим: кадр и так приходит не чаще раза в 80 мс.
    window.addEventListener('resize', schedule, { passive: true });
    // Шрифт подменяется после первой отрисовки, и знакоместо меняет ширину.
    if (document.fonts && document.fonts.ready) document.fonts.ready.then(schedule);
  }

  root.AsciiFigures = { shapes: Object.keys(MAPS), redraw: schedule, mount: mount };

  if (document.readyState === 'loading')
    document.addEventListener('DOMContentLoaded', mount);
  else mount();
})(window);
