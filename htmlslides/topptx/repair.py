"""Промах по таблице: собрать геометрию из измеренного варианта-донора.

Зачем это вообще нужно. Таблица перебирает оси раскладки, и по осям «какие
слоты заполнены» и «сколько элементов в списке» перебор полный. Но шесть
шаблонов каталога ветвятся ВНУТРИ элемента списка — `{% if cell.heading %}` в
grid-2x2, то же в cards-6, frames-grid, stats-row, two-col-cards, kpi. У ряда из
пяти ячеек с одним необязательным заголовком это 2^5 деревьев на одну длину
списка, у grid-2x2 с тремя рядами — 2^15, и это только при максимальных длинах.
Перебрать такое нельзя: калибровка и так идёт 95 секунд на 1651 дереве.

А эталонная дека перебирает лишь два крайних случая: доп. под-слоты есть у ВСЕХ
элементов либо ни у одного. Замер: из 34 случайных смесей 14 не нашлись в
таблице, то есть 14 слайдов из PPTX бы просто исчезли.

Почему донор, а не браузер. Браузер на экспорте дал бы точную геометрию, но
стоит он 300 МБ и полсекунды на страницу, а требование к сервису — автономность
и скромный расход. Донор не стоит ничего: нужный вариант уже измерен и уже
загружен в память.

Донор — измеренный вариант того же шаблона, чьё дерево СОДЕРЖИТ дерево реального
слайда. Содержит — ключевое слово: тогда недостающие элементы остаётся только
выбросить, а выдумывать геометрию для элемента, которого не мерили, не придётся
ни разу. Такой донор есть всегда, потому что вариант «доп. под-слоты у всех»
перебирается по тем же осям длин и drop'ов, что и реальный слайд, и по построению
оказывается его надмножеством.

Что остаётся приблизительным. Выброс элемента поднимает то, что было под ним, —
это считает reflow.drop тем же распространением, что сверено с браузером на
94212 рамках. Чего поправка НЕ знает: случаев, когда исчезновение элемента меняет
не только высоты, но и саму раскладку (перенос flex-строки, другое число колонок
в grid). Поэтому починка — не замена калибровке, а страховка от пропажи слайда:
измеренный вариант всегда точнее починенного, и если ось можно перебрать, её надо
перебрать, а не починить.
"""
from __future__ import annotations

from .domkey import element_children
from .reflow import children_of, drop, elastic_paths


def _sig_el(el) -> tuple[str, str]:
    """Чем элемент разметки опознаётся среди соседей: тег и классы."""
    return el.tag, el.get("class") or ""


def _sig_row(row: dict) -> tuple[str, str]:
    """То же для строки таблицы. Поля `t` и `c` для этого и сохраняются."""
    return row["t"], row.get("c") or ""


def _order(path: str) -> tuple[int, ...]:
    """Путь как кортеж чисел: "1.10" идёт ПОСЛЕ "1.2", а не до него."""
    return tuple(int(n) for n in path.split("."))


def align(section, variant: dict) -> tuple[dict[str, str], list[str]] | None:
    """Сопоставить пути слайда путям донора. -> (карта, лишние у донора) | None.

    Сопоставление идёт по подпоследовательности детей у каждого родителя: дети
    реального слайда должны идти у донора в том же порядке, а между ними донор
    может иметь свои — те самые необязательные элементы, которых на слайде нет.
    Повторы (пять ячеек с одним классом) этому не мешают: различаются соседи
    ровно необязательными элементами, и жадный проход по порядку даёт
    единственное сопоставление.

    Сравнивать по путям нельзя: пути позиционные, и ячейка без заголовка держит
    свой текст по индексу 0, а с заголовком — по индексу 1. Поэтому карта, а не
    совпадение путей.

    Внутрь <svg> не идём: позиции там расставил автор, в таблицу эти элементы не
    попадают вовсе (см. structure_fingerprint), и сверять там нечего.
    """
    by_path = {r["p"]: r for r in variant["items"]}
    dkids = children_of(by_path)
    mapping: dict[str, str] = {}
    extra: list[str] = []

    def rec(el, aprefix: str, dpath: str) -> bool:
        group = dkids.get(dpath, [])
        j = 0
        for i, child in enumerate(element_children(el)):
            apath = f"{aprefix}.{i}" if aprefix else str(i)
            want = _sig_el(child)
            while j < len(group) and _sig_row(by_path[group[j]]) != want:
                extra.append(group[j])
                j += 1
            if j == len(group):
                return False       # донор этого элемента не содержит — не донор
            mapping[apath] = group[j]
            if child.tag != "svg" and not rec(child, apath, group[j]):
                return False
            j += 1
        extra.extend(group[j:])
        return True

    return (mapping, extra) if rec(section, "", "") else None


def donor(section, variants: list[dict]) -> tuple[dict, dict[str, str],
                                                  list[str]] | None:
    """Ближайший подходящий вариант. -> (вариант, карта, лишние) | None.

    «Ближайший» — у которого лишних элементов меньше всех: чем меньше выброшено,
    тем меньше поправок, а каждая поправка — приближение. Вариант с нулём лишних
    означал бы точное совпадение дерева, но такой нашёлся бы ещё по ключу, так
    что сюда мы попадаем только когда лишние есть.
    """
    best = None
    for var in variants:
        got = align(section, var)
        if got is None:
            continue
        mapping, extra = got
        if best is None or len(extra) < len(best[2]):
            best = (var, mapping, extra)
    return best


def rows_for(section, variants: list[dict],
             styles: list[dict]) -> tuple[list[dict], dict] | None:
    """Строки геометрии для слайда, которого нет в таблице. -> (строки, донор).

    Возвращает строки уже под ПУТИ РЕАЛЬНОГО слайда, так что вызывающему
    различать починенный вариант от найденного не нужно — дальше работает
    обычный reflow_apply по настоящему тексту.
    """
    got = donor(section, variants)
    if got is None:
        return None
    variant, mapping, extra = got

    rows = [dict(r) for r in variant["items"]]
    by_path = {r["p"]: r for r in rows}
    kids = children_of(by_path)
    # Признак «высота по содержимому» снимается с НЕИСПОРЧЕННОЙ таблицы, до
    # любых выбросов, — по той же причине, по которой это делает reflow.apply:
    # у родителя уже поправленного ребёнка сумма перестанет сходиться, и
    # признак перевернётся.
    elastic = elastic_paths(by_path, kids, styles)

    # В обратном порядке документа. На результат порядок не влияет: в extra
    # попадают только КОРНИ непарных поддеревьев, вложенных друг в друга там
    # нет, а дельта каждого считается по текущему inner_height родителя — то
    # есть уже с учётом ранее выброшенных. Но детерминированным он быть обязан,
    # иначе одна и та же дека дала бы разный PPTX.
    for path in sorted(extra, key=_order, reverse=True):
        drop(path, by_path, kids, styles, elastic)

    out = []
    for apath, dpath in mapping.items():
        row = by_path[dpath]
        if row.get("off"):
            continue                 # выброшен: на слайде такого элемента нет
        row = dict(row)
        row["p"] = apath
        out.append(row)
        # Псевдостроки ("::b"/"::a") в children_of не входят, значит и в
        # mapping не попадают — переезжают вслед за своим элементом. Иначе
        # донорская починка молча теряла бы сепараторы three-col и замыкающую
        # линию timeline.
        for sfx in ("::b", "::a"):
            prow = by_path.get(dpath + sfx)
            if prow is not None:
                prow = dict(prow)
                prow["p"] = apath + sfx
                out.append(prow)
    return out, variant
