"""Сохранность фактуры: числа исходника, не доехавшие до слайда.

ЗАЧЕМ ЭТО ЕСТЬ. Промпт филлера прямо требует беречь цифры: «цифры и факты
РЕЗУЛЬТАТА обязаны попасть в слоты», «сохраняй значащие суффиксы: 152-ФЗ, а НЕ
152». Требование заявлено — и никем не проверялось. Замер на шести реальных
деках (`data/e2e/`) показал медиану 0.38 по доле дошедших чисел, причём на двух
деках — 0.00. Дека при этом выглядит безупречно: слайд заполнен, вёрстка
чистая, линтер молчит. Потерялась только фактура, а это единственное, что на
слайде нельзя пересочинить.

Проверка детерминированная: ни LLM, ни браузера, миллисекунды на деку. Находка
здесь — СОВЕТ, а не отказ: сборку она не роняет, а кладёт замечание в тот же
круг автофикса, куда уже идут замечания линтера и vision-QA.

ПОЧЕМУ ЗАМЕЧАНИЕ НЕСЁТ САМИ ЗНАЧЕНИЯ. `autofix_slide` работает без исходника:
после заполнения бриф из `content` стёрт, и `filler._brief()` подсовывает
модели её же контент. Сказать «ты потерял числа» бесполезно — вернуть их
неоткуда. Поэтому detail перечисляет пропавшее дословно.

ЧТО НЕ СЧИТАЕТСЯ ФАКТОМ (замерено, каждое правило снимало ложные срабатывания):
- служебная шапка брифа «Слайд N» — номер источника, не контент (44% ложных);
- ссылки и блок `[Sources]` — в URL живут числа вроде `/10-steps/`;
- `01`/`02`/`03` — нумерация разделов;
- одиночная цифра без процента — счётчик или маркер списка.

ЧАСТИЧНАЯ ПОТЕРЯ — НЕ ДЕФЕКТ. Пересказ обязан сокращать, и слайд, донёсший
часть чисел, работу сделал. Замечание выдаётся, только когда не дошло НИ ОДНО
число (замерено: 13 слайдов из 81) либо потеряно три и больше (ещё 2).
"""
from __future__ import annotations

import re

from .linter import LintIssue

#: Служебная шапка брифа из pptx-парсера: «Слайд 12», «Slide 3».
_HEADER = re.compile(r"^\s*(?:слайд|slide)\s*\d+\s*", re.I)
#: Блок ссылок в конце брифа — источники, а не фактура слайда.
_SOURCES = re.compile(r"\[Sources\].*", re.S | re.I)
_URL = re.compile(r"https?://\S+|\bwww\.\S+")
#: Число с разделителями тысяч и необязательным процентом: 1 200 · 99,95% · 3.2.1
_TOKEN = re.compile(
    r"(?P<num>\d{1,3}(?:[  ]\d{3})+(?:[.,]\d+)?|\d+(?:[.,]\d+)*)"
    r"(?P<pct>\s?%)?")
#: Столько потерянных чисел на слайде считаем провалом даже при частичной потере.
_MANY_LOST = 3


def _flat(text: str) -> str:
    """Убрать разделители тысяч: «1 200» и «1200» — одно и то же число."""
    return re.sub(r"[  ]", "", text)


def extract_facts(text: str) -> set[str]:
    """Числа исходника, которые нельзя терять при пересказе."""
    text = _URL.sub(" ", _SOURCES.sub(" ", _HEADER.sub("", text or "")))
    facts: set[str] = set()
    for match in _TOKEN.finditer(text):
        num = _flat(match.group("num"))
        pct = bool(match.group("pct"))
        digits = re.sub(r"\D", "", num)
        if not digits:
            continue
        if len(digits) == 2 and digits[0] == "0" and not pct:
            continue                      # 01/02/03 — нумерация разделов
        if len(digits) < 2 and not pct:
            continue                      # одиночная цифра — счётчик
        facts.add(num + ("%" if pct else ""))
    return facts


def _reached(fact: str, slide_text: str) -> bool:
    """Факт дошёл, если его цифровое ядро есть в тексте слайда.

    Сравниваем по ядру, а не по написанию: «152» засчитывается и в «152-ФЗ», и в
    «ФЗ-152». Требовать точного совпадения строки значило бы ругаться на слайд,
    который оформил число правильнее исходника.
    """
    return re.sub(r"\D", "", fact) in _flat(slide_text)


def slide_texts(html: str) -> list[str]:
    """Видимый текст каждого слайда собранной деки, ВКЛЮЧАЯ подписи внутри <svg>.

    Выбрасывать svg нельзя: слайды-диаграммы рисуются целиком в нём, и на замере
    именно они давали ложные «потери» — числа были на слайде, просто внутри svg.
    """
    body = re.sub(r"<script[\s\S]*?</script>", " ", html)
    out: list[str] = []
    for part in re.split(r"<section\b", body)[1:]:
        part = part.split("</section>")[0]
        part = re.sub(r"<style[\s\S]*?</style>", " ", part)
        part = re.sub(r"<[^>]+>", " ", part).replace("&nbsp;", " ")
        out.append(re.sub(r"\s+", " ", part).strip())
    return out


def check_facts(plan, html: str) -> list[LintIssue]:
    """Замечания «фактура не доехала». Пустой список = сверять было нечего или всё дошло.

    Слайды без брифа молча пропускаются: сверять их не с чем (так приходят деки,
    собранные из черновика, а не из документа).
    """
    texts = slide_texts(html)
    issues: list[LintIssue] = []
    for slide in plan.slides:
        brief = getattr(slide, "brief", "") or ""
        position = slide.index - 1
        if not brief or not 0 <= position < len(texts):
            continue
        facts = extract_facts(brief)
        if not facts:
            continue
        missing = sorted(f for f in facts if not _reached(f, texts[position]))
        if not missing:
            continue
        if len(missing) < len(facts) and len(missing) < _MANY_LOST:
            continue                      # часть чисел ушла при сокращении — норма
        issues.append(LintIssue(
            slide.index, "facts_lost",
            "в слоты не попали числа исходника: " + ", ".join(missing)
            + " — верни их дословно, с единицами и суффиксами "
              "(«152-ФЗ», а не «152»), ничего не выдумывая"))
    return issues
