"""Сгенерировать крупный технический .md для нагрузочных прогонов пайплайна.

Прод-таймауты 2026-07-28 воспроизводились только на документах, где планировщик
раскладывается в СОТНИ слайдов: там включаются потолок MAX_DECK_SLIDES, пул
хвостовых фаз и мягкий дедлайн. Держать чужой исходник в репо нельзя (это
клиентский документ), а PrivateTmp чистится рестартом — поэтому эквивалент по
объёму и структуре генерируем сами.

    python scripts/gen_large_doc.py out.md --kb 140
"""
from __future__ import annotations

import argparse
import random

TOPICS = [
    "Резервное копирование", "Аварийное восстановление", "Репликация томов",
    "Снапшоты кластера", "Сетевые политики", "Балансировка нагрузки",
    "Мониторинг и алертинг", "Журналирование", "Управление секретами",
    "Контроль доступа", "Шифрование данных", "Миграция баз данных",
    "Оркестрация контейнеров", "Автомасштабирование", "Тестирование отказов",
    "Планирование мощностей", "Стоимость владения", "Регламент дежурств",
    "Инвентаризация ресурсов", "Согласование с ИБ",
]
ASPECTS = ["архитектура", "процесс", "метрики", "риски", "план внедрения",
           "эксплуатация", "стоимость"]


def _paragraph(rnd: random.Random, topic: str, aspect: str) -> str:
    bits = [
        f"{topic} в контуре Cloud.ru опирается на региональную пару площадок и "
        f"согласованный RPO. Раздел описывает {aspect} и границы ответственности.",
        "Целевое состояние фиксируется в реестре сервисов, отклонения разбираются "
        "на еженедельном ревью архитектуры и попадают в бэклог платформенной команды.",
        "Переход выполняется волнами: сначала стенды и предпрод, затем продуктивные "
        "нагрузки уровня B, и только после стабилизации метрик — критичные системы.",
        "Ограничения фиксируются заранее: окна обслуживания, квоты на трафик между "
        "зонами доступности и лимиты параллельных операций на стороне хранилища.",
    ]
    rnd.shuffle(bits)
    return " ".join(bits)


def _section(rnd: random.Random, n: int) -> str:
    topic = TOPICS[n % len(TOPICS)]
    aspect = ASPECTS[n % len(ASPECTS)]
    out = [f"## {n}. {topic}: {aspect}", "", _paragraph(rnd, topic, aspect), ""]
    out += ["### Что делаем", ""]
    out += [f"- Шаг {i}: {topic.lower()} — проверяем {rnd.choice(ASPECTS)} и "
            f"фиксируем результат в протоколе." for i in range(1, 6)]
    out += ["", "### Показатели", "",
            "| Показатель | Текущее | Целевое | Срок |",
            "|---|---|---|---|"]
    out += [f"| Метрика {i} | {rnd.randint(40, 90)}% | {rnd.randint(91, 99)}% | "
            f"Q{rnd.randint(1, 4)} |" for i in range(1, 5)]
    out += ["", _paragraph(rnd, topic, "риски"), ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--kb", type=int, default=140)
    ap.add_argument("--seed", type=int, default=20260728)
    args = ap.parse_args()

    rnd = random.Random(args.seed)
    parts = ["# Программа миграции резервного копирования и аварийного "
             "восстановления", "",
             "Документ описывает целевую архитектуру, план перехода и "
             "эксплуатационный регламент.", ""]
    n = 1
    target = args.kb * 1024          # в БАЙТАХ: кириллица — 2 байта на символ,
    size = 0                         # по символам объём вышел бы вдвое больше
    while size < target:
        section = _section(rnd, n)
        parts.append(section)
        size += len(section.encode("utf-8")) + 1
        n += 1
    text = "\n".join(parts)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"{args.out}: {len(text.encode('utf-8'))} bytes, {n - 1} sections")


if __name__ == "__main__":
    main()
